"""Writes ``src/CMToolkit.Core/PythonSemantics/PythonCaseFold.Table.cs``: every code point whose ``str.casefold()`` is
not itself, with what it folds to, from the Python that runs this script.

Run it with the Reference Implementation's interpreter (the parity driver's python.org 3.14, ``unicodedata`` 16.0.0)
when that interpreter's Unicode version changes:

    python dotnet/eng/generate-casefold.py

The table is the whole of Python's full case folding, so the port never depends on .NET's own (simple, culture-aware
or ICU-versioned) case mappings for the Archive Patcher's name filter (AP-2).
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "CMToolkit.Core" / "PythonSemantics" / "PythonCaseFold.Table.cs"


def literal(text: str) -> str:
	"""A C# string literal of ``text``, ASCII-only: letters and digits as is, everything else escaped."""
	parts = []
	for char in text:
		code = ord(char)
		if char.isascii() and char.isalnum():
			parts.append(char)
		elif code <= 0xFFFF:
			parts.append(f"\\u{code:04X}")
		else:
			parts.append(f"\\U{code:08X}")
	return '"' + "".join(parts) + '"'


def main() -> None:
	"""Writes the table."""
	folds = [
		(code, chr(code).casefold())
		for code in range(0x110000)
		if not 0xD800 <= code <= 0xDFFF and chr(code).casefold() != chr(code)
	]
	version = f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"
	lines = [
		"// <auto-generated>",
		f"// Generated by dotnet/eng/generate-casefold.py from Python {version} (Unicode {unicodedata.unidata_version}).",
		"// Do not edit: rerun the script.",
		"// </auto-generated>",
		"",
		"namespace CMToolkit.Core.PythonSemantics;",
		"",
		"public static partial class PythonCaseFold",
		"{",
		"    /// <summary>The Unicode version of Python's <c>unicodedata</c> the table was generated from.</summary>",
		f'    public const string UnicodeVersion = "{unicodedata.unidata_version}";',
		"",
		"    /// <summary>The code points that fold to something else, ascending.</summary>",
		"    private static readonly int[] Folded =",
		"    [",
		*(f"        0x{code:04X}," for code, _ in folds),
		"    ];",
		"",
		'    /// <summary>What each code point in <see cref="Folded"/> folds to, at the same index.</summary>',
		"    private static readonly string[] FoldedTo =",
		"    [",
		*(f"        {literal(value)}," for _, value in folds),
		"    ];",
		"}",
	]
	OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
	print(f"{OUT}: {len(folds)} code points")


if __name__ == "__main__":
	main()
